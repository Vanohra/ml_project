"""
run_experiments.py
------------------
Launcher and documentation for the three controlled experiments that answer:

    "Does adding realistic degradation modeling and degradation-aware
     conditioning improve super-resolution compared to a simple bicubic/
     SRCNN baseline?"

Three experiments, three models:
  Bicubic     — non-ML baseline (no training needed)
  SimpleSRCNN — ~57k params, learns corrections over bicubic upscaling
  SRResNet    — ~957k params, residual blocks + PixelShuffle upsampling

--------------------------------------------------------------------------
  Experiment 1 — Bicubic vs SimpleSRCNN (clean LR)
  Experiment 2 — SimpleSRCNN: realistic vs clean degradation
  Experiment 3 — SimpleSRCNN vs SRResNet (realistic degradation)
--------------------------------------------------------------------------

Usage (from ml_project/ directory):
  python scripts/run_experiments.py             # print descriptions + commands
  python scripts/run_experiments.py --run 1     # launch Experiment 1
  python scripts/run_experiments.py --run 2     # launch Experiment 2
  python scripts/run_experiments.py --run 3     # launch Experiment 3
  python scripts/run_experiments.py --run all   # launch all three in sequence
"""

import argparse
import subprocess
import sys
from pathlib import Path

PROJECT_DIR = Path(__file__).resolve().parent.parent
SCRIPTS_DIR = Path(__file__).resolve().parent


# -- Experiment descriptions ----------------------------------------------------

