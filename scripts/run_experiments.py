    for num, exp in EXPERIMENTS.items():
        print(f"\n{'-' * 70}")
        print(f"  Experiment {num}: {exp['title']}")
        print(f"{'-' * 70}")
        print(f"  Research question : {exp['question']}")
        print(f"  LR generation     : {exp['lr_generation']}")
        print(f"  Models            : {exp['models']}")
        print(f"  Epochs            : {exp['epochs']}")
        print(f"\n  Context:\n  {exp['notes']}")

    print(f"\n{'-' * 70}")
    print("  Summary table (run AFTER all experiments + evaluate.py):")
    print(f"{'-' * 70}")
    print("  Method          PSNR (dB)    SSIM")
    print("  Bicubic           xx.xx       x.xxx")
    print("  SimpleSRCNN       xx.xx       x.xxx")
    print("  SRResNet          xx.xx       x.xxx")
    print(f"\n  Run: python scripts/evaluate.py")
    print("=" * 70)


